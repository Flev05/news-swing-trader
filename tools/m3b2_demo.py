"""Disposable M3B2 demo. Run with the repository-managed Python from the repository root."""
from __future__ import annotations

import http.client
import json
import os
from pathlib import Path
import queue
import re
import subprocess
import tempfile
import threading
import time
import uuid
from datetime import UTC, datetime, timedelta

ROOT = Path(__file__).resolve().parents[1]


def run(*command: str) -> str:
    return subprocess.check_output(command, cwd=ROOT, text=True, timeout=120).strip()


def main() -> None:
    uv = ROOT / ".tools/uv/0.12.9/uv"
    if not uv.is_file() or not (ROOT / "apps/ai-worker/.venv/bin/python").is_file():
        raise SystemExit("Run make bootstrap in WSL Ubuntu first.")
    print("COMMAND ./mvnw -q -f apps/core-java -DskipTests package", flush=True)
    subprocess.run(["./mvnw", "-q", "-f", "apps/core-java", "-DskipTests", "package"],
                   cwd=ROOT, check=True, timeout=120)
    name = "m3b2-demo-" + uuid.uuid4().hex
    container = None
    java = None
    reader = None
    with tempfile.TemporaryDirectory(prefix="m3b2-demo-") as directory:
        try:
            print(f"COMMAND docker run --rm --name {name} -d "
                  "-e POSTGRES_HOST_AUTH_METHOD=trust -p 127.0.0.1::5432 postgres:18.6", flush=True)
            container = run("docker", "run", "--rm", "--name", name, "-d",
                            "-e", "POSTGRES_HOST_AUTH_METHOD=trust", "-p", "127.0.0.1::5432",
                            "postgres:18.6")
            mapping = run("docker", "port", container, "5432/tcp")
            db_port = int(mapping.rsplit(":", 1)[1])
            # Poll only readiness, with an absolute deadline; no business assertion is retried.
            deadline = time.monotonic() + 30
            while subprocess.run(["docker", "exec", container, "pg_isready", "-U", "postgres"],
                                 stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                                 timeout=3).returncode != 0:
                if time.monotonic() >= deadline:
                    raise RuntimeError("Disposable PostgreSQL readiness deadline")
                threading.Event().wait(0.1)
            args = ["java", "-jar", "apps/core-java/target/core-java-0.0.1-SNAPSHOT.jar",
                    "--server.port=0", f"--spring.datasource.url=jdbc:postgresql://127.0.0.1:{db_port}/postgres",
                    "--spring.datasource.username=postgres", "--spring.datasource.password="]
            print("COMMAND " + " ".join(args), flush=True)
            java = subprocess.Popen(args, cwd=ROOT, stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True)
            ports: queue.Queue[int] = queue.Queue()
            log_path = Path(directory) / "java.log"

            def read_log() -> None:
                assert java is not None and java.stdout is not None
                with log_path.open("w") as log:
                    for line in java.stdout:
                        log.write(line)
                        match = re.search(r"Tomcat started on port ([0-9]+)", line)
                        if match:
                            ports.put(int(match.group(1)))

            reader = threading.Thread(target=read_log)
            reader.start()
            port = ports.get(timeout=45)
            now = datetime.now(UTC)

            def stamp(value: datetime) -> str:
                return value.isoformat().replace("+00:00", "Z")

            event = {
                "schema_version": "1.0.0", "event_id": str(uuid.uuid4()),
                "correlation_id": str(uuid.uuid4()),
                "source": {"provider": "demo_wire", "news_id": name, "revision_id": "1",
                           "canonical_url": "https://example.test/m3b2-demo"},
                "source_created_at": stamp(now - timedelta(seconds=30)),
                "source_updated_at": stamp(now - timedelta(seconds=20)),
                "received_at": stamp(now), "deadline_at": stamp(now + timedelta(minutes=10)),
                "headline": "Synthetic M3B2 abstention demonstration",
                "content": {"language": "en", "summary": "Synthetic fixture only."},
                "affected_symbols": ["ACME", "BETA"],
            }
            print(f"COMMAND HTTP POST http://127.0.0.1:{port}/api/v1/news-events "
                  "(synthetic event generated by this script)", flush=True)
            connection = http.client.HTTPConnection("127.0.0.1", port, timeout=10)
            try:
                connection.request("POST", "/api/v1/news-events", json.dumps(event),
                                   {"Content-Type": "application/json"})
                response = connection.getresponse()
                admission = json.loads(response.read())
                assert response.status == 202, response.status
                job = admission["job"]["job_id"]
                print(f"HTTP 202 job_id={job}", flush=True)
            finally:
                connection.close()
            worker = [str(uv), "run", "--directory", "apps/ai-worker", "--locked", "--no-sync",
                      "--offline", "python", "-m", "news_swing_ai.worker",
                      "--base-url", f"http://127.0.0.1:{port}", "--once"]
            print("COMMAND " + " ".join(worker), flush=True)
            env = dict(os.environ, UV_CACHE_DIR=str(ROOT / ".tools/cache"),
                       UV_PYTHON_INSTALL_DIR=str(ROOT / ".tools/python"))
            completed = subprocess.run(worker, cwd=ROOT, env=env, text=True,
                                       capture_output=True, timeout=30, check=True)
            print(completed.stdout.strip(), flush=True)
            print("worker exit=0", flush=True)
            sql = ("SELECT j.status, j.assignment_count, count(r.job_id), "
                   "min(r.result_payload->'model'->>'name') FROM trader.inference_jobs j "
                   "LEFT JOIN trader.inference_results r ON r.job_id=j.job_id "
                   f"WHERE j.job_id='{job}'::uuid GROUP BY j.status,j.assignment_count;")
            print(f"COMMAND docker exec {container} psql -U postgres -d postgres -At -c "
                  + repr(sql), flush=True)
            observed = run("docker", "exec", container, "psql", "-U", "postgres", "-d", "postgres",
                           "-At", "-c", sql)
            print(observed, flush=True)
            assert observed == "SUCCEEDED|1|1|deterministic-abstention"
        finally:
            if java is not None:
                java.terminate()
                try:
                    java.wait(timeout=10)
                except subprocess.TimeoutExpired:
                    java.kill()
                    java.wait(timeout=5)
                if reader is not None:
                    reader.join(5)
                    assert not reader.is_alive()
                if java.stdout is not None:
                    java.stdout.close()
                print("CLEANUP Java process stopped", flush=True)
            if container:
                print(f"COMMAND docker rm -fv {container}", flush=True)
                # --rm may already have removed it; inspect only our recorded container ID.
                removed = subprocess.run(["docker", "rm", "-fv", container],
                                         capture_output=True, text=True, timeout=15)
                if removed.returncode and "No such container" not in removed.stderr:
                    raise RuntimeError("Disposable container cleanup failed")
                print("CLEANUP disposable container and its anonymous volume removed", flush=True)
    print("CLEANUP temporary logs removed; developer Compose database untouched", flush=True)


if __name__ == "__main__":
    main()
